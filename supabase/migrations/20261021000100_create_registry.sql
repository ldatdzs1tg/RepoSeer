-- Apply once with Supabase SQL Editor or the Supabase migration workflow.
-- PRIVATE schema; not a ready-to-use worker API.
-- Never store GitHub tokens, DB passwords, or raw crawl payloads here.

BEGIN;

CREATE SCHEMA IF NOT EXISTS reposeer;
REVOKE ALL ON SCHEMA reposeer FROM PUBLIC;

-- Fixed worker slots. Names remain unassigned until the coordinator decides.
CREATE TABLE IF NOT EXISTS reposeer.workers (
    worker_id text PRIMARY KEY
        CHECK (worker_id ~ '^(D1|D2|C[1-7])$'),
    worker_role text NOT NULL
        CHECK (worker_role IN ('discovery', 'screening', 'crawler')),
    display_name text,
    is_enabled boolean NOT NULL DEFAULT false,
    last_seen_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Repositories exist as candidates before GitHub verification.
-- github_repo_id becomes the stable identity after verification.
CREATE TABLE IF NOT EXISTS reposeer.repositories (
    repository_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_full_name text NOT NULL,
    github_repo_id bigint UNIQUE,
    verification_status text NOT NULL DEFAULT 'candidate'
        CHECK (verification_status IN ('candidate', 'verified_current', 'unavailable')),
    verified_at timestamptz,
    last_collected_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (verification_status <> 'verified_current' OR github_repo_id IS NOT NULL)
);
CREATE UNIQUE INDEX IF NOT EXISTS repositories_name_ci_uq
    ON reposeer.repositories (lower(repo_full_name));

-- Package identity is the RepoSeer canonical `pypi:<normalized-name>` key.
-- Verified current mapping does NOT imply historical validity.
CREATE TABLE IF NOT EXISTS reposeer.packages (
    package_id text PRIMARY KEY
        CHECK (package_id ~ '^pypi:[a-z0-9]+(-[a-z0-9]+)*$'),
    first_sampling_run_id uuid,
    source_snapshot_sha256 text
        CHECK (source_snapshot_sha256 IS NULL OR source_snapshot_sha256 ~ '^[a-f0-9]{64}$'),
    mapping_status text NOT NULL DEFAULT 'not_checked'
        CHECK (mapping_status IN ('not_checked', 'candidate', 'verified_current', 'unresolved')),
    candidate_repo_full_name text,
    repository_id bigint REFERENCES reposeer.repositories(repository_id),
    last_screened_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    CHECK (mapping_status <> 'verified_current' OR repository_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS packages_repository_idx
    ON reposeer.packages (repository_id)
    WHERE repository_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS packages_mapping_status_idx
    ON reposeer.packages (mapping_status);

-- One logical job per operation + target + scope_key.
-- A different scope_key permits an intentional later refresh.
CREATE TABLE IF NOT EXISTS reposeer.crawl_jobs (
    job_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    job_kind text NOT NULL
        CHECK (job_kind IN ('screen_package', 'verify_repository', 'collect_repository')),
    package_id text REFERENCES reposeer.packages(package_id),
    repository_id bigint REFERENCES reposeer.repositories(repository_id),
    scope_key text NOT NULL DEFAULT 'initial',
    priority integer NOT NULL DEFAULT 0,
    status text NOT NULL DEFAULT 'queued'
        CHECK (status IN ('queued', 'claimed', 'retry', 'completed', 'failed')),
    claimed_by text REFERENCES reposeer.workers(worker_id),
    claim_token uuid,
    claimed_at timestamptz,
    lease_expires_at timestamptz,
    retry_after timestamptz,
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    max_attempts integer NOT NULL DEFAULT 3 CHECK (max_attempts >= 1),
    last_error_code text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (btrim(scope_key) <> ''),
    CHECK (
        (job_kind = 'screen_package' AND package_id IS NOT NULL AND repository_id IS NULL)
        OR (job_kind IN ('verify_repository', 'collect_repository')
            AND repository_id IS NOT NULL AND package_id IS NULL)
    ),
    CHECK (
        status <> 'claimed'
        OR (claimed_by IS NOT NULL AND claim_token IS NOT NULL
            AND lease_expires_at IS NOT NULL)
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS crawl_jobs_package_scope_uq
    ON reposeer.crawl_jobs (job_kind, package_id, scope_key)
    WHERE package_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS crawl_jobs_repository_scope_uq
    ON reposeer.crawl_jobs (job_kind, repository_id, scope_key)
    WHERE repository_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS crawl_jobs_queue_idx
    ON reposeer.crawl_jobs (status, priority DESC, created_at);
CREATE INDEX IF NOT EXISTS crawl_jobs_lease_idx
    ON reposeer.crawl_jobs (lease_expires_at)
    WHERE status = 'claimed';

-- Short run summaries only. Full manifests and raw data live on Google Drive.
CREATE TABLE IF NOT EXISTS reposeer.crawl_runs (
    run_id uuid PRIMARY KEY,
    worker_id text REFERENCES reposeer.workers(worker_id),
    job_id uuid REFERENCES reposeer.crawl_jobs(job_id),
    run_kind text NOT NULL
        CHECK (run_kind IN ('sampling', 'screening', 'integration', 'github_activity', 'ingestion')),
    status text NOT NULL DEFAULT 'running'
        CHECK (status IN ('running', 'complete', 'partial', 'failed', 'interrupted')),
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    error_code text,
    CHECK (finished_at IS NULL OR finished_at >= started_at)
);
CREATE INDEX IF NOT EXISTS crawl_runs_job_idx
    ON reposeer.crawl_runs (job_id, started_at DESC);
CREATE INDEX IF NOT EXISTS crawl_runs_worker_idx
    ON reposeer.crawl_runs (worker_id, started_at DESC);

-- Artifact metadata only: files are stored in Google Drive.
CREATE TABLE IF NOT EXISTS reposeer.artifacts (
    artifact_id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    run_id uuid NOT NULL REFERENCES reposeer.crawl_runs(run_id),
    artifact_kind text NOT NULL
        CHECK (artifact_kind IN ('bundle', 'manifest', 'raw', 'processed', 'profile')),
    storage_path text NOT NULL UNIQUE,
    sha256 text NOT NULL CHECK (sha256 ~ '^[a-f0-9]{64}$'),
    byte_size bigint CHECK (byte_size IS NULL OR byte_size >= 0),
    status text NOT NULL DEFAULT 'submitted'
        CHECK (status IN ('submitted', 'verified', 'ingested', 'rejected')),
    submitted_at timestamptz NOT NULL DEFAULT now(),
    ingested_at timestamptz,
    error_code text
);
CREATE INDEX IF NOT EXISTS artifacts_run_idx
    ON reposeer.artifacts (run_id);
CREATE INDEX IF NOT EXISTS artifacts_status_idx
    ON reposeer.artifacts (status);

-- Defense in depth. This schema is deliberately NOT exposed to PostgREST,
-- and no RLS policy is added for anon/authenticated users.
ALTER TABLE reposeer.workers ENABLE ROW LEVEL SECURITY;
ALTER TABLE reposeer.repositories ENABLE ROW LEVEL SECURITY;
ALTER TABLE reposeer.packages ENABLE ROW LEVEL SECURITY;
ALTER TABLE reposeer.crawl_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE reposeer.crawl_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE reposeer.artifacts ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON ALL TABLES IN SCHEMA reposeer FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA reposeer FROM PUBLIC, anon, authenticated;

INSERT INTO reposeer.workers (worker_id, worker_role)
VALUES
    ('D1', 'discovery'),
    ('D2', 'screening'),
    ('C1', 'crawler'),
    ('C2', 'crawler'),
    ('C3', 'crawler'),
    ('C4', 'crawler'),
    ('C5', 'crawler'),
    ('C6', 'crawler'),
    ('C7', 'crawler')
ON CONFLICT (worker_id) DO NOTHING;

COMMIT;


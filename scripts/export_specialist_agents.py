"""Export additive D07 input/output/review JSON Schemas; --check never writes."""

import argparse
import json
from pathlib import Path

from reposeer.contracts.specialist_agents import (
    AGENT_SCHEMA_VERSION,
    REQUEST_ADAPTER,
    RESPONSE_ADAPTER,
    REVIEW_ADAPTER,
)

ROOT = Path(__file__).resolve().parents[1]


def generate_artifacts() -> dict[str, bytes]:
    adapters = {
        "specialist_agent_input.schema.json": REQUEST_ADAPTER,
        "specialist_agent_output.schema.json": RESPONSE_ADAPTER,
        "specialist_conflict_review.schema.json": REVIEW_ADAPTER,
    }
    result = {}
    for filename, adapter in adapters.items():
        schema = adapter.json_schema()
        schema.update({
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$comment": f"Generated by scripts/export_specialist_agents.py; contract={AGENT_SCHEMA_VERSION}; generator=1",
            "description": "Structural schema. Temporal, quote and cross-boundary checks require specialist_agents.py validators.",
        })
        result[filename] = (json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n").encode("utf-8")
    return result


def check_artifacts(directory: Path, artifacts: dict[str, bytes]) -> list[str]:
    return [
        name for name, expected in artifacts.items()
        if not (directory / name).is_file()
        or (directory / name).read_bytes().replace(b"\r\n", b"\n") != expected
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    artifacts = generate_artifacts()
    directory = ROOT / "docs/contracts"
    if args.check:
        drift = check_artifacts(directory, artifacts)
        if drift:
            print("Specialist agent schema drift: " + ", ".join(drift))
            return 1
        print("Specialist agent schemas match models")
    else:
        for name, content in artifacts.items():
            (directory / name).write_bytes(content)
        print("Generated specialist agent input/output/review schemas")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

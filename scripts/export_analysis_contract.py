"""Export the additive analysis contract; --check detects drift without writes."""

import argparse
import json
from pathlib import Path

from reposeer.contracts.analysis import ANALYSIS_SCHEMA_VERSION, FINAL_REPORT_ADAPTER

if __package__:
    from scripts.export_contract import ts_type
else:
    from export_contract import ts_type

ROOT = Path(__file__).resolve().parents[1]


def generate_artifacts() -> dict[str, bytes]:
    generator = f"scripts/export_analysis_contract.py; analysis={ANALYSIS_SCHEMA_VERSION}; generator=1"
    schema = FINAL_REPORT_ADAPTER.json_schema()
    schema.update({
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$comment": "Generated by " + generator,
        "title": "RepoSeer Analysis Contract " + ANALYSIS_SCHEMA_VERSION,
        "description": "FinalReport discriminated by result_status. Cross-field, temporal and reference checks require validate_final_report.",
    })
    ts = [
        "// Generated by " + generator + ". Do not edit.",
        "// Run validate_final_report at the producer boundary; narrow result_status in the UI.",
        "",
    ]
    for name, definition in sorted(schema["$defs"].items()):
        rendered = ts_type(definition)
        if definition.get("type") == "object" and "properties" in definition:
            ts.append(f"export interface {name} {{")
            required = set(definition.get("required", []))
            for field, value in sorted(definition["properties"].items()):
                optional = "" if field in required else "?"
                ts.append(f"  {field}{optional}: {ts_type(value)};")
            ts.append("}")
        else:
            ts.append(f"export type {name} = {rendered};")
        ts.append("")
    ts.append("export type FinalReport = " + ts_type({"oneOf": schema["oneOf"]}) + ";")
    return {
        "analysis_contract.schema.json": (
            json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
        ).encode("utf-8"),
        "analysis_types.ts": ("\n".join(ts) + "\n").encode("utf-8"),
    }


def check_artifacts(directory: Path, artifacts: dict[str, bytes]) -> list[str]:
    # New artifacts have no entry in the existing .gitattributes. Accept checkout
    # line endings on Windows without modifying that file or weakening drift checks.
    return [
        name for name, expected in artifacts.items()
        if not (directory / name).is_file()
        or (directory / name).read_bytes().replace(b"\r\n", b"\n") != expected
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    artifacts = generate_artifacts()
    directory = ROOT / "docs/contracts"
    if args.check:
        drift = check_artifacts(directory, artifacts)
        if drift:
            print("Analysis contract artifact drift: " + ", ".join(drift))
            return 1
        print("Analysis contract artifacts match canonical models")
    else:
        for name, content in artifacts.items():
            (directory / name).write_bytes(content)
        print("Generated analysis JSON Schema and TypeScript")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

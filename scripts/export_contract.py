"""Generate all contract artifacts from Pydantic; --check never writes files."""

import argparse
import json
from pathlib import Path

from pydantic import TypeAdapter

from reposeer.contracts import CONTRACT_ADAPTER, SCHEMA_VERSION, NormalizedRecord

ROOT = Path(__file__).resolve().parents[1]
GENERATOR = f"scripts/export_contract.py; contract={SCHEMA_VERSION}; generator=1"
ANNOTATIONS = {
    "title",
    "description",
    "examples",
    "default",
    "format",
    "pattern",
    "minLength",
    "maxLength",
    "minimum",
    "maximum",
    "exclusiveMinimum",
    "exclusiveMaximum",
    "multipleOf",
    "minItems",
    "maxItems",
    "uniqueItems",
    "discriminator",
    "$defs",
    "$schema",
    "$comment",
}
SHAPES = {
    "$ref",
    "type",
    "const",
    "enum",
    "anyOf",
    "oneOf",
    "properties",
    "required",
    "additionalProperties",
    "items",
}


def ts_type(schema: dict) -> str:
    unsupported = set(schema) - ANNOTATIONS - SHAPES
    if unsupported:
        raise ValueError(f"Unsupported JSON Schema keywords: {sorted(unsupported)}")
    if "$ref" in schema:
        if not schema["$ref"].startswith("#/$defs/"):
            raise ValueError("Only local $defs references are supported")
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(value, ensure_ascii=False) for value in schema["enum"])
    for union in ("anyOf", "oneOf"):
        if union in schema:
            return " | ".join(ts_type(item) for item in schema[union])
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(ts_type({**schema, "type": item}) for item in kind)
    scalar = {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }
    if kind in scalar:
        return scalar[kind]
    if kind == "array":
        if "items" not in schema:
            raise ValueError("Array schema requires items")
        return f"Array<{ts_type(schema['items'])}>"
    if kind == "object":
        properties = schema.get("properties", {})
        required = set(schema.get("required", []))
        members = [
            f"{json.dumps(name)}{'' if name in required else '?'}: {ts_type(value)};"
            for name, value in sorted(properties.items())
        ]
        extra = schema.get("additionalProperties", True)
        if extra is not False:
            value = ts_type(extra) if isinstance(extra, dict) else "unknown"
            members.append(f"[key: string]: {value};")
        return "{ " + " ".join(members) + " }"
    if not schema:
        return "unknown"  # Actual unconstrained JSON only, never a fallback for unsupported shapes.
    raise ValueError(f"Unsupported JSON Schema shape: {schema}")


def generate_artifacts() -> dict[str, bytes]:
    schema = CONTRACT_ADAPTER.json_schema()
    schema.update(
        {
            "$schema": "https://json-schema.org/draft/2020-12/schema",
            "$comment": "Generated by " + GENERATOR,
            "title": "RepoSeer Data Contract " + SCHEMA_VERSION,
            "description": "Structural schema; semantic invariants require reposeer.contracts.models and validation.",
        }
    )
    definitions = schema["$defs"]
    ts = [
        "// Generated by " + GENERATOR + ". Do not edit.",
        "// Runtime semantic checks remain mandatory in Python.",
        "",
    ]
    reference = [
        "# Contract schema reference",
        "",
        "Generated by `" + GENERATOR + "`. Do not edit.",
        "",
        "Required nullable fields must still be present. Semantic validators are mandatory.",
        "",
    ]
    for name, definition in sorted(definitions.items()):
        # Check each shape, including nested field constraints.
        rendered = ts_type(definition)
        if (
            definition.get("type") == "object"
            and "properties" in definition
            and definition.get("additionalProperties") is False
        ):
            ts.append(f"export interface {name} {{")
            required = set(definition.get("required", []))
            reference.extend(
                [
                    f"## {name}",
                    "",
                    "| Field | Required | Nullable | Type / enum |",
                    "| --- | --- | --- | --- |",
                ]
            )
            for field, value in sorted(definition["properties"].items()):
                field_type = ts_type(value)
                optional = "" if field in required else "?"
                ts.append(f"  {field}{optional}: {field_type};")
                nullable = value.get("type") == "null" or any(
                    item.get("type") == "null" for item in value.get("anyOf", [])
                )
                safe_type = field_type.replace("|", "&#124;")
                reference.append(
                    f"| `{field}` | {'yes' if field in required else 'no'} | {'yes' if nullable else 'no'} | `{safe_type}` |"
                )
            ts.extend(["}", ""])
            reference.append("")
        else:
            ts.extend([f"export type {name} = {rendered};", ""])
            reference.extend([f"## {name}", "", "`" + rendered.replace("|", "&#124;") + "`", ""])
    ts.extend(
        [
            "export type ContractRecord = " + ts_type({"oneOf": schema["oneOf"]}) + ";",
            "export type NormalizedRecord = "
            + ts_type(TypeAdapter(NormalizedRecord).json_schema())
            + ";",
            "",
        ]
    )
    for name, method, request, result in (
        ("Collector", "collect", "CollectionRequest", "CollectionResult"),
        ("Normalizer", "normalize", "NormalizationRequest", "NormalizationResult"),
        ("TechnologyLinker", "link", "TechnologyLinkRequest", "TechnologyLinkResult"),
        ("SnapshotBuilder", "build", "SnapshotBuildRequest", "SnapshotBuildResult"),
    ):
        ts.extend(
            [
                f"export interface {name} {{",
                f"  {method}(request: {request}): Promise<{result}>;",
                "}",
                "",
            ]
        )
    return {
        "data_contract.schema.json": (
            json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
        ).encode("utf-8"),
        "types.ts": ("\n".join(ts).rstrip() + "\n").encode("utf-8"),
        "schema_reference.md": ("\n".join(reference).rstrip() + "\n").encode("utf-8"),
    }


def check_artifacts(directory: Path, artifacts: dict[str, bytes]) -> list[str]:
    return [
        name
        for name, expected in artifacts.items()
        if not (directory / name).is_file() or (directory / name).read_bytes() != expected
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    artifacts = generate_artifacts()
    directory = ROOT / "docs/contracts"
    if args.check:
        drift = check_artifacts(directory, artifacts)
        if drift:
            print("Contract artifact drift: " + ", ".join(drift))
            return 1
        print("Contract artifacts match canonical models")
    else:
        for name, content in artifacts.items():
            (directory / name).write_bytes(content)
        print("Generated schema, TypeScript and schema reference")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
